def _classify(component):
    text = component.get_name().lower()
    try:
        mesh = component.get_editor_property("static_mesh")
        if mesh:
            text += " " + mesh.get_path_name().lower()
    except Exception:
        pass
    if "grass" in text:
        return "grass"
    if any(token in text for token in ["flower", "fern", "leaf", "plant"]):
        return "plant"
    if any(token in text for token in ["tree", "pine", "conifer"]):
        return "tree"
    if any(token in text for token in ["rock", "stone", "boulder"]):
        return "rock"
    return "other"


def _clamp_angle(value, limit=5.0):
    while value > 180.0:
        value -= 360.0
    while value < -180.0:
        value += 360.0
    return max(-limit, min(limit, value))


def _actor_tags(actor):
    try:
        return [str(tag) for tag in actor.tags]
    except Exception:
        return []


def _tagged_as_block(actor, component=None):
    tags = _actor_tags(actor)
    if component is not None:
        tags.extend(_component_tags(component))
    return any("block" in tag.lower() for tag in tags)


def _component_world_bounds(component):
    try:
        origin = component.bounds.origin
        extent = component.bounds.box_extent
        return origin, extent, "component_bounds"
    except Exception:
        pass

    try:
        local_min, local_max = component.get_local_bounds()
    except Exception:
        return None

    corners = [
        unreal.Vector(x, y, z)
        for x in [local_min.x, local_max.x]
        for y in [local_min.y, local_max.y]
        for z in [local_min.z, local_max.z]
    ]
    world_points = []
    try:
        transform = component.get_component_transform()
    except Exception:
        transform = None
    for corner in corners:
        point = None
        if transform is not None:
            try:
                point = transform.transform_position(corner)
            except Exception:
                point = None
        if point is None:
            try:
                owner = component.get_owner()
                location = owner.get_actor_location()
                scale = owner.get_actor_scale3d()
                point = unreal.Vector(
                    location.x + corner.x * scale.x,
                    location.y + corner.y * scale.y,
                    location.z + corner.z * scale.z,
                )
            except Exception:
                continue
        world_points.append(point)
    if not world_points:
        return None
    min_x = min(point.x for point in world_points)
    max_x = max(point.x for point in world_points)
    min_y = min(point.y for point in world_points)
    max_y = max(point.y for point in world_points)
    min_z = min(point.z for point in world_points)
    max_z = max(point.z for point in world_points)
    origin = unreal.Vector((min_x + max_x) * 0.5, (min_y + max_y) * 0.5, (min_z + max_z) * 0.5)
    extent = unreal.Vector((max_x - min_x) * 0.5, (max_y - min_y) * 0.5, (max_z - min_z) * 0.5)
    return origin, extent, "local_bounds"


def _collect_block_bounds():
    bounds = []
    seen = set()
    for actor in unreal.EditorLevelLibrary.get_all_level_actors():
        actor_is_block = _tagged_as_block(actor)
        for component in actor.get_components_by_class(unreal.StaticMeshComponent):
            if not actor_is_block and not _tagged_as_block(actor, component):
                continue
            resolved = _component_world_bounds(component)
            if not resolved:
                continue
            origin, extent, source = resolved
            key = (
                actor.get_path_name(),
                component.get_name(),
                round(float(origin.x), 3),
                round(float(origin.y), 3),
                round(float(origin.z), 3),
                round(float(extent.x), 3),
                round(float(extent.y), 3),
                round(float(extent.z), 3),
            )
            if key in seen:
                continue
            seen.add(key)
            bounds.append(
                {
                    "actor": actor.get_actor_label(),
                    "component": component.get_name(),
                    "origin": [float(origin.x), float(origin.y), float(origin.z)],
                    "extent": [float(extent.x), float(extent.y), float(extent.z)],
                    "bounds_source": source,
                }
            )
    return bounds


def _inside_block(location, block_bounds, margin=120.0):
    for entry in block_bounds or []:
        origin = entry.get("origin") or [0.0, 0.0, 0.0]
        extent = entry.get("extent") or [0.0, 0.0, 0.0]
        if (
            abs(location.x - origin[0]) <= extent[0] + margin
            and abs(location.y - origin[1]) <= extent[1] + margin
        ):
            return True
    return False


def _stabilize_component(component, category, material):
    if category == "grass" and material:
        try:
            component.set_material(0, material)
        except Exception:
            pass
    tags = _component_tags(component)
    for tag in ["PCGClosedSplineAreaGenerated", "PCG_GrassArea"]:
        if tag not in tags:
            tags.append(tag)
    _set_component_tags(component, tags)

    changed = 0
    count = int(component.get_instance_count())
    for index in range(count):
        try:
            transform = component.get_instance_transform(index, False)
            rotator = transform.rotation.rotator()
            pitch = _clamp_angle(rotator.pitch)
            roll = _clamp_angle(rotator.roll)
            if abs(pitch - rotator.pitch) > 0.01 or abs(roll - rotator.roll) > 0.01:
                transform.rotation = _make_rotator(pitch, rotator.yaw, roll).quaternion()
                if component.update_instance_transform(index, transform, False, False, True):
                    changed += 1
        except Exception:
            pass
    try:
        component.mark_render_state_dirty()
    except Exception:
        pass
    return changed


def _validate(source_actor, spline, generated_actor):
    polygon = _world_polygon(source_actor)
    block_bounds = _collect_block_bounds()
    grass_material = unreal.EditorAssetLibrary.load_asset(GRASS_MATERIAL_PATH)
    summary = {
        "spline_closed_loop": bool(spline.is_closed_loop()),
        "spline_point_count": int(spline.get_number_of_spline_points()),
        "polygon": [[round(x, 1), round(y, 1)] for x, y in polygon],
        "block_tagged_component_count": len(block_bounds),
        "components": {},
        "instances": {},
        "inside_count": 0,
        "outside_violation_count": 0,
        "outside_samples": [],
        "block_overlap_violation_count": 0,
        "block_overlap_samples": [],
        "pitch_roll_violation_count_after": 0,
        "pitch_roll_clamped_instances": 0,
        "mesh_rows": [],
        "output_meshes": [],
    }

    generated_owner = generated_actor or source_actor
    positive_meshes = set()
    for component in generated_owner.get_components_by_class(unreal.InstancedStaticMeshComponent):
        category = _classify(component)
        count = int(component.get_instance_count())
        mesh_path = None
        try:
            mesh_path = _object_path(component.get_editor_property("static_mesh"))
        except Exception:
            pass
        if count > 0 and mesh_path:
            positive_meshes.add(mesh_path)
        summary["mesh_rows"].append(
            {
                "component": component.get_name(),
                "category": category,
                "mesh": mesh_path,
                "count": count,
            }
        )
        summary["components"][category] = summary["components"].get(category, 0) + 1
        summary["instances"][category] = summary["instances"].get(category, 0) + count
        summary["pitch_roll_clamped_instances"] += _stabilize_component(
            component, category, grass_material
        )

        for index in range(count):
            try:
                world_transform = component.get_instance_transform(index, True)
                location = world_transform.translation
                local_transform = component.get_instance_transform(index, False)
                rotator = local_transform.rotation.rotator()
            except Exception:
                continue

            if abs(_clamp_angle(rotator.pitch) - rotator.pitch) > 0.01:
                summary["pitch_roll_violation_count_after"] += 1
            if abs(_clamp_angle(rotator.roll) - rotator.roll) > 0.01:
                summary["pitch_roll_violation_count_after"] += 1

            if _point_in_polygon(location.x, location.y, polygon):
                summary["inside_count"] += 1
            else:
                summary["outside_violation_count"] += 1
                if len(summary["outside_samples"]) < 20:
                    summary["outside_samples"].append(
                        {
                            "component": component.get_name(),
                            "category": category,
                            "index": index,
                            "location": [
                                round(location.x, 1),
                                round(location.y, 1),
                                round(location.z, 1),
                            ],
                        }
                    )

            if _inside_block(location, block_bounds):
                summary["block_overlap_violation_count"] += 1
                if len(summary["block_overlap_samples"]) < 20:
                    summary["block_overlap_samples"].append(
                        {
                            "component": component.get_name(),
                            "category": category,
                            "index": index,
                            "location": [
                                round(location.x, 1),
                                round(location.y, 1),
                                round(location.z, 1),
                            ],
                        }
                    )

    summary["generated_instance_total"] = sum(summary["instances"].values())
    summary["output_meshes"] = sorted(positive_meshes)
    try:
        requested_override = bool(source_actor.get_editor_property("UseGrassMeshOverride"))
        actor_property_mesh = _object_path(source_actor.get_editor_property("GrassMeshOverride"))
    except Exception:
        requested_override = USE_GRASS_MESH_OVERRIDE
        actor_property_mesh = None
    summary["mesh_override"] = {
        "requested": requested_override,
        "actor_property_mesh": actor_property_mesh,
        "output_meshes": summary["output_meshes"],
        "actor_property_mesh_override_pass": (
            not requested_override
            or (
                bool(summary["output_meshes"])
                and summary["output_meshes"] == [actor_property_mesh]
            )
        ),
    }
    summary["pass"] = (
        summary["spline_closed_loop"]
        and summary["spline_point_count"] >= 3
        and summary["generated_instance_total"] > 0
        and summary["outside_violation_count"] == 0
        and summary["block_overlap_violation_count"] == 0
        and summary["pitch_roll_violation_count_after"] == 0
        and summary["mesh_override"]["actor_property_mesh_override_pass"]
    )
    return summary


def _write_report(report):
    out_dir = os.path.join(unreal.Paths.project_saved_dir(), "MCP_PCG")
    os.makedirs(out_dir, exist_ok=True)
    report_path = os.path.join(out_dir, REPORT_NAME)
    with open(report_path, "w", encoding="utf-8") as handle:
        json.dump(report, handle, indent=2, ensure_ascii=False)
    print(json.dumps({"report": report_path, **report}, ensure_ascii=False))
    return report_path


def _finish(state):
    actor = _find_actor(ACTOR_LABEL)
    if not actor:
        raise RuntimeError("Fixture source actor disappeared: " + ACTOR_LABEL)
    pcg_actor = _find_actor(PCG_VOLUME_LABEL)
    if not pcg_actor:
        raise RuntimeError("Fixture PCGVolume disappeared: " + PCG_VOLUME_LABEL)
    splines = actor.get_components_by_class(unreal.SplineComponent)
    if not splines:
        raise RuntimeError("Fixture actor has no SplineComponent at finish.")
    validation = _validate(actor, splines[0], pcg_actor)
    try:
        unreal.EditorLevelLibrary.save_current_level()
        save_current_level = True
    except Exception as exc:
        save_current_level = "failed: " + str(exc)

    report = {
        "timestamp": time.strftime("%Y-%m-%d %H:%M:%S"),
        "world": unreal.EditorLevelLibrary.get_editor_world().get_path_name(),
        "fixture_actor": ACTOR_LABEL,
        "pcg_volume_actor": PCG_VOLUME_LABEL,
        "policy": {
            "open_spline": "roads, fences, guides, borders, clear masks, density gradients, and other linear placement; 2-point splines are valid here",
            "closed_spline": "3+ point area masks for grass/groundcover generation",
        },
        "implementation_expectation": {
            "linear_spline_support_must_remain": True,
            "closed_area_spline_requires_dedicated_sampling": True,
            "candidate_bp_reuse_is_only_a_probe": True,
        },
        "level_load": state.get("level_load", {}),
        "deleted_existing": state.get("deleted_existing", 0),
        "blueprint_update": state.get("blueprint_update", {}),
        "graph_update": state.get("graph_update", {}),
        "source_actor_properties": state.get("source_actor_properties", {}),
        "source_pcg_components": state.get("source_pcg_components", []),
        "pcg_components": state.get("pcg_components", []),
        "pcg_generation": state.get("pcg_generation", []),
        "validation": validation,
        "save_current_level": save_current_level,
    }
    report["pass"] = bool(validation.get("pass"))
    return _write_report(report)


def validate_closed_spline_grass_area():
    previous_state = getattr(unreal, STATE_ATTR, None)
    if previous_state and previous_state.get("handle"):
        try:
            unreal.unregister_slate_post_tick_callback(previous_state["handle"])
        except Exception:
            pass

    level_load = _load_level()
    world = unreal.EditorLevelLibrary.get_editor_world()
    deleted_existing = _delete_existing()

    actor_class = unreal.load_object(None, BP_CLASS_PATH)
    if not actor_class:
        raise RuntimeError("Missing actor class: " + BP_CLASS_PATH)
    graph = unreal.load_object(None, GRASS_GRAPH_PATH)
    if not graph:
        raise RuntimeError("Missing grass graph: " + GRASS_GRAPH_PATH)
    blueprint_update = _ensure_blueprint_grass_override_variables()
    graph_update = _ensure_closed_grass_graph_mesh_override(graph)

    origin_x = 23800.0
    origin_y = 25300.0
    origin_z, hit_landscape = _sample_ground_z(world, origin_x, origin_y, 0.0)
    source_actor = unreal.EditorLevelLibrary.spawn_actor_from_class(
        actor_class,
        unreal.Vector(origin_x, origin_y, origin_z),
        _make_rotator(0.0, -12.0, 0.0),
    )
    if not source_actor:
        raise RuntimeError("Failed to spawn closed spline grass actor.")
    source_actor.set_actor_label(ACTOR_LABEL)
    source_actor_properties = _apply_grass_mesh_override_properties(
        source_actor,
        USE_GRASS_MESH_OVERRIDE,
    )
    try:
        source_actor.set_editor_property(
            "tags",
            [
                unreal.Name("PCGClosedSplineArea"),
                unreal.Name("PCGGrassArea"),
                unreal.Name("MCPValidation"),
            ],
        )
    except Exception:
        pass

    source_pcg_components = _deactivate_source_pcg(source_actor)

    pcg_actor = unreal.EditorLevelLibrary.spawn_actor_from_class(
        unreal.PCGVolume,
        unreal.Vector(origin_x, origin_y, origin_z + 500.0),
        _make_rotator(0.0, 0.0, 0.0),
    )
    if not pcg_actor:
        raise RuntimeError("Failed to spawn closed spline grass PCGVolume.")
    pcg_actor.set_actor_label(PCG_VOLUME_LABEL)
    try:
        pcg_actor.set_actor_scale3d(unreal.Vector(120.0, 120.0, 20.0))
    except Exception:
        pass
    try:
        pcg_actor.set_editor_property(
            "tags",
            [
                unreal.Name("MCPValidation"),
                unreal.Name("PCGClosedSplineAreaVolume"),
            ],
        )
    except Exception:
        pass

    state = {
        "started_at": time.time(),
        "generation_started_at": None,
        "handle": None,
        "completed": False,
        "generated_after_settle": False,
        "level_load": level_load,
        "deleted_existing": deleted_existing,
        "hit_landscape": hit_landscape,
        "pcg_volume_actor": PCG_VOLUME_LABEL,
        "blueprint_update": blueprint_update,
        "graph_update": graph_update,
        "source_actor_properties": source_actor_properties,
        "source_pcg_components": source_pcg_components,
        "pcg_components": [],
        "pcg_generation": [],
    }

    def _tick(_delta_seconds):
        if state["completed"]:
            return False
        elapsed = time.time() - state["started_at"]
        if not state["generated_after_settle"]:
            if elapsed < 0.75:
                return True
            settled_source = _find_actor(ACTOR_LABEL)
            settled_pcg = _find_actor(PCG_VOLUME_LABEL)
            if not settled_source or not settled_pcg:
                state["completed"] = True
                _write_report(
                    {
                        "timestamp": time.strftime("%Y-%m-%d %H:%M:%S"),
                        "pass": False,
                        "status": "failed",
                        "error": "settled source or PCGVolume actor missing before generation",
                        "source_found": bool(settled_source),
                        "pcg_volume_found": bool(settled_pcg),
                    }
                )
                return False
            state["source_actor_properties"] = _apply_grass_mesh_override_properties(
                settled_source,
                USE_GRASS_MESH_OVERRIDE,
            )
            _configure_spline(settled_source)
            state["pcg_components"] = _configure_pcg(settled_pcg, graph)
            # The configure pass can trigger PCG component setup side effects;
            # apply the closed spline again after that settle point and before
            # the actual validation generation.
            state["source_actor_properties"] = _apply_grass_mesh_override_properties(
                settled_source,
                USE_GRASS_MESH_OVERRIDE,
            )
            _configure_spline(settled_source)
            state["pcg_generation"] = _generate_enabled_pcg(settled_pcg)
            state["generation_started_at"] = time.time()
            state["generated_after_settle"] = True
            return True

        if time.time() - float(state["generation_started_at"] or state["started_at"]) < WAIT_SECONDS:
            return True
        state["completed"] = True
        try:
            unreal.unregister_slate_post_tick_callback(state["handle"])
        except Exception:
            pass
        try:
            state["report_path"] = _finish(state)
        except Exception as exc:
            _write_report(
                {
                    "timestamp": time.strftime("%Y-%m-%d %H:%M:%S"),
                    "pass": False,
                    "status": "failed",
                    "error": str(exc),
                    "level_load": state.get("level_load", {}),
                    "pcg_components": state.get("pcg_components", []),
                }
            )
        return False

    state["handle"] = unreal.register_slate_post_tick_callback(_tick)
    setattr(unreal, STATE_ATTR, state)

    scheduled = {
        "timestamp": time.strftime("%Y-%m-%d %H:%M:%S"),
        "status": "scheduled",
        "wait_seconds": WAIT_SECONDS,
        "fixture_actor": ACTOR_LABEL,
        "pcg_volume_actor": PCG_VOLUME_LABEL,
        "level_load": level_load,
        "deleted_existing": deleted_existing,
        "hit_landscape": hit_landscape,
        "blueprint_update": blueprint_update,
        "graph_update": graph_update,
        "source_actor_properties": source_actor_properties,
        "pcg_components": [],
        "pcg_generation": [],
        "generation_deferred_until_after_spawn_settle": True,
    }
    print(json.dumps(scheduled, ensure_ascii=False))
    return scheduled


