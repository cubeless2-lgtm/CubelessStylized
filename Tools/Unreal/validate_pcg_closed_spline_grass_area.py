def _generate_enabled_pcg(actor):
    rows = []
    components = list(actor.get_components_by_class(unreal.PCGComponent))
    enabled_names = {"PCG_Style"} if any(c.get_name() == "PCG_Style" for c in components) else set()
    if not enabled_names and components:
        enabled_names.add(components[0].get_name())
    for component in components:
        name = component.get_name()
        enabled = name in enabled_names
        row = {"component": name, "enabled": enabled}
        if not enabled:
            rows.append(row)
            continue
        try:
            component.activate(True)
            component.cleanup(True)
            component.generate(True)
            try:
                component.generate_local(True)
            except Exception as local_exc:
                row["generate_local_error"] = str(local_exc)
            row["generated"] = True
        except Exception as exc:
            row["generated"] = False
            row["error"] = str(exc)
        rows.append(row)
    return rows


