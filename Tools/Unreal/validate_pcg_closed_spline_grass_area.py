"""Validate grass generation constrained by a closed spline area.

This is a fixture for the required PCG rule:
- open splines, including 2-point splines, are valid for roads, fences, guides,
  borders, masks, gradients, and other linear placement
- closed splines with at least 3 points are area masks; grass/groundcover must
  spawn inside them

The script uses the existing PCG ecosystem candidate Blueprint and a grass graph
so the output is still generated by PCG components, then validates generated ISM
instance positions against the closed polygon.
"""

