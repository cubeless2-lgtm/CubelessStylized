def _sample_ground_z(world, x, y, fallback_z=0.0):
    start = unreal.Vector(x, y, 50000.0)
    end = unreal.Vector(x, y, -10000.0)
    try:
        hit = unreal.SystemLibrary.line_trace_single(
            world,
            start,
            end,
            unreal.TraceTypeQuery.TRACE_TYPE_QUERY1,
            False,
            [],
            unreal.DrawDebugTrace.NONE,
            True,
        )
        values = hit.to_tuple()
    except Exception:
        return fallback_z, False

    if not values or not bool(values[0]):
        return fallback_z, False
    try:
        actor = values[9]
        actor_name = actor.get_name() if actor else ""
        actor_class = actor.get_class().get_name() if actor else ""
    except Exception:
        actor_name = ""
        actor_class = ""
    if "Landscape" not in actor_name and "Landscape" not in actor_class:
        return fallback_z, False
    try:
        return float(values[4].z), True
    except Exception:
        return fallback_z, False


def _configure_spline(actor):
    splines = actor.get_components_by_class(unreal.SplineComponent)
    if not splines:
        raise RuntimeError("Fixture actor has no SplineComponent.")
    spline = splines[0]
    spline.clear_spline_points(False)
    for point in LOCAL_POLYGON:
        spline.add_spline_point(point, unreal.SplineCoordinateSpace.LOCAL, False)
    for index in range(spline.get_number_of_spline_points()):
        try:
            spline.set_spline_point_type(index, unreal.SplinePointType.LINEAR, False)
        except Exception:
            pass
    spline.set_closed_loop(True, False)
    spline.update_spline()
    try:
        spline.set_editor_property(
            "component_tags",
            [unreal.Name("PCGClosedSplineArea"), unreal.Name("PCGGrassArea")],
        )
    except Exception:
        pass
    return spline


def _world_polygon(actor):
    location = actor.get_actor_location()
    rotation = actor.get_actor_rotation()
    yaw = math.radians(float(rotation.yaw))
    cos_yaw = math.cos(yaw)
    sin_yaw = math.sin(yaw)
    points = []
    for point in LOCAL_POLYGON:
        x = location.x + point.x * cos_yaw - point.y * sin_yaw
        y = location.y + point.x * sin_yaw + point.y * cos_yaw
        points.append((float(x), float(y)))
    return points


def _point_in_polygon(x, y, polygon):
    inside = False
    count = len(polygon)
    j = count - 1
    for i in range(count):
        xi, yi = polygon[i]
        xj, yj = polygon[j]
        crosses = (yi > y) != (yj > y)
        if crosses:
            x_at_y = (xj - xi) * (y - yi) / ((yj - yi) or 1e-9) + xi
            if x < x_at_y:
                inside = not inside
        j = i
    return inside


