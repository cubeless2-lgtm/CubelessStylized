def _road_spline(actor):
    splines = list(actor.get_components_by_class(unreal.SplineComponent))
    if not splines:
        raise RuntimeError("Road actor has no SplineComponent.")
    for spline in splines:
        if spline.get_name() == "Road_SourceSpline":
            return spline
    return splines[0]


def _tag_spline(spline):
    try:
        tags = list(spline.get_editor_property("component_tags"))
    except Exception:
        tags = []
    names = {str(tag) for tag in tags}
    if ROAD_SPLINE_TAG not in names:
        tags.append(unreal.Name(ROAD_SPLINE_TAG))
        spline.set_editor_property("component_tags", tags)


def _route_points(route_name):
    if route_name == "A":
        return [
            unreal.Vector(GRID_ORIGIN.x - 3600.0, GRID_ORIGIN.y, GRID_ORIGIN.z),
            unreal.Vector(GRID_ORIGIN.x + 3600.0, GRID_ORIGIN.y, GRID_ORIGIN.z),
        ]
    if route_name == "B":
        return [
            unreal.Vector(GRID_ORIGIN.x + 1600.0, GRID_ORIGIN.y - 3100.0, GRID_ORIGIN.z),
            unreal.Vector(GRID_ORIGIN.x + 1600.0, GRID_ORIGIN.y + 3100.0, GRID_ORIGIN.z),
        ]
    raise ValueError("Unknown route: " + str(route_name))


def _set_route(actor, route_name):
    spline = _road_spline(actor)
    _tag_spline(spline)
    points = _route_points(route_name)
    spline.clear_spline_points(False)
    for point in points:
        spline.add_spline_point(point, unreal.SplineCoordinateSpace.WORLD, False)
    for index in range(spline.get_number_of_spline_points()):
        try:
            spline.set_spline_point_type(index, unreal.SplinePointType.LINEAR, False)
        except Exception:
            pass
    spline.set_closed_loop(False, False)
    spline.update_spline()
    try:
        actor.modify()
        spline.modify()
    except Exception:
        pass
    return {
        "route": route_name,
        "point_count": int(spline.get_number_of_spline_points()),
        "length_cm": round(float(spline.get_spline_length()), 2),
        "points": [[round(p.x, 2), round(p.y, 2), round(p.z, 2)] for p in points],
    }


def _generate(pcg_actor):
    rows = []
    for component in pcg_actor.get_components_by_class(unreal.PCGComponent):
        row = {"component": component.get_name()}
        try:
            component.activate(True)
            component.cleanup(True)
            component.generate(True)
            try:
                component.generate_local(True)
            except Exception as local_exc:
                row["generate_local_error"] = str(local_exc)
            row["generated"] = True
        except Exception as exc:
            row["generated"] = False
            row["error"] = str(exc)
        rows.append(row)
    return rows


def _segments(route_name):
    points = _route_points(route_name)
    segments = []
    for index in range(len(points) - 1):
        a = points[index]
        b = points[index + 1]
        dx = float(b.x - a.x)
        dy = float(b.y - a.y)
        length_sq = dx * dx + dy * dy
        if length_sq > 1.0:
            segments.append((float(a.x), float(a.y), dx, dy, length_sq))
    return segments


def _distance_to_route(x, y, route_name):
    best = float("inf")
    for ax, ay, dx, dy, length_sq in _segments(route_name):
        t = max(0.0, min(1.0, ((x - ax) * dx + (y - ay) * dy) / length_sq))
        px = ax + dx * t
        py = ay + dy * t
        dist_sq = (x - px) * (x - px) + (y - py) * (y - py)
        best = min(best, math.sqrt(dist_sq))
    return best


def _instance_locations(actor):
    locations = []
    components = []
    for component in actor.get_components_by_class(unreal.InstancedStaticMeshComponent):
        try:
            count = int(component.get_instance_count())
        except Exception:
            count = 0
        components.append({"component": component.get_name(), "count": count})
        for index in range(count):
            try:
                transform = component.get_instance_transform(index, True)
                loc = transform.translation
                locations.append((float(loc.x), float(loc.y), float(loc.z)))
            except Exception:
                pass
    return locations, components


def _collect_phase(pcg_actor, route_name):
    locations, components = _instance_locations(pcg_actor)
    near_a = []
    near_b = []
    restored_old_a = []
    for index, (x, y, z) in enumerate(locations):
        dist_a = _distance_to_route(x, y, "A")
        dist_b = _distance_to_route(x, y, "B")
        if dist_a < ROAD_CLEARANCE_CM:
            near_a.append((index, dist_a, x, y, z))
        if dist_b < ROAD_CLEARANCE_CM:
            near_b.append((index, dist_b, x, y, z))
        if dist_a < ROAD_CLEARANCE_CM and dist_b >= ROAD_CLEARANCE_CM * 1.2:
            restored_old_a.append((index, dist_a, dist_b, x, y, z))
    active_near = near_a if route_name == "A" else near_b
    inactive_near = near_b if route_name == "A" else near_a
    return {
        "route": route_name,
        "instance_total": len(locations),
        "components": components,
        "active_route_violation_count": len(active_near),
        "near_route_a_count": len(near_a),
        "near_route_b_count": len(near_b),
        "inactive_route_near_count": len(inactive_near),
        "restored_old_a_count": len(restored_old_a),
        "sample_locations": [
            [round(x, 2), round(y, 2), round(z, 2)]
            for x, y, z in locations[:20]
        ],
        "active_violation_samples": [
            {
                "index": item[0],
                "distance_cm": round(item[1], 2),
                "location": [round(item[2], 2), round(item[3], 2), round(item[4], 2)],
            }
            for item in active_near[:20]
        ],
        "restored_old_a_samples": [
            {
                "index": item[0],
                "distance_a_cm": round(item[1], 2),
                "distance_b_cm": round(item[2], 2),
                "location": [round(item[3], 2), round(item[4], 2), round(item[5], 2)],
            }
            for item in restored_old_a[:20]
        ],
    }


def _dirty_packages():
    rows = []
