"""Validate graph-owned road-aware forest clear/refill behavior.

This fixture proves the production target before touching ecosystem graph
families: forest points are generated by a PCG graph, a runtime road spline is
read as PCG data, and moving the road spline clears the new corridor while
allowing the previous corridor to refill on regeneration.
"""

